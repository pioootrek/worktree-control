const messages = { pl, en };
export type TranslationKey = keyof typeof pl;
export type Translate = (key: TranslationKey, values?: TranslationValues) => string;

export function translate(locale: Locale, key: TranslationKey, values: TranslationValues = {}): string {
  return Object.entries(values).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    messages[locale][key],
  );
}

export function localeFrom(value: string | null | undefined): Locale {
  return value?.toLowerCase().startsWith("pl") ? "pl" : "en";
}

export function systemLocale(environment: Readonly<Record<string, string | undefined>>): Locale {
  return localeFrom(environment.LC_ALL ?? environment.LC_MESSAGES ?? environment.LANG);
}

export function dashboardSummary(locale: Locale, running: number, projects: number): string {
  if (locale === "en") {
    return `${running} active · ${projects} ${projects === 1 ? "project" : "projects"}`;
  }

  const usesPaucal = (count: number) => (
    count % 10 >= 2 && count % 10 <= 4 && (count % 100 < 12 || count % 100 > 14)
  );
  const active = running === 1 ? "aktywny" : usesPaucal(running) ? "aktywne" : "aktywnych";
  const project = projects === 1 ? "projekt" : usesPaucal(projects) ? "projekty" : "projektów";
  return `${running} ${active} · ${projects} ${project}`;
}
